# ---------- abuse protection: rate limits, size limit, security headers ----------
_HITS: dict = {}
# Number of trusted reverse proxies in front of the app. 0 keeps the old behaviour (first X-Forwarded-For
# entry, which a client can spoof); set 1 on a platform whose proxy appends the real client IP last.
PROXY_HOPS = int(os.getenv("AURORA_PROXY_HOPS", "0") or 0)


@app.middleware("http")
async def _guard(request: Request, call_next):
    xff = [p.strip() for p in request.headers.get("x-forwarded-for", "").split(",") if p.strip()]
    if PROXY_HOPS and len(xff) >= PROXY_HOPS:
        ip = xff[-PROXY_HOPS]
    else:
        ip = (xff[0] if xff else "") or (request.client.host if request.client else "?")
    now, path = time.time(), request.url.path
    strict = request.method == "POST" and any(k in path for k in ("login", "register", "password", "forgot", "verify", "google", "/auth"))
    key = (ip, strict)
    hits = [t for t in _HITS.get(key, []) if now - t < 60] + [now]
    _HITS[key] = hits
    if len(_HITS) > 5000:
        for k in [k for k, v in _HITS.items() if not v or now - v[-1] > 60]:
            _HITS.pop(k, None)

    def deny(code, msg):
        r = JSONResponse({"detail": msg}, status_code=code)
        if request.headers.get("origin"):
            r.headers["Access-Control-Allow-Origin"] = request.headers["origin"]
        return r

    if len(hits) > (20 if strict else 300):
        return deny(429, "Too many requests. Please slow down and try again in a minute.")
    try:
        clen = int(request.headers.get("content-length") or 0)
    except ValueError:
        clen = 0
    if clen > 13_000_000:
        return deny(413, "Request too large.")
    resp = await call_next(request)
    resp.headers["X-Content-Type-Options"] = "nosniff"
    resp.headers["Referrer-Policy"] = "no-referrer"
    resp.headers["Strict-Transport-Security"] = "max-age=31536000"
    return resp
