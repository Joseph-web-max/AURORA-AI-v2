@app.post("/auth/register")
@app.post("/api/auth/register")
@app.post("/api/v1/auth/register")
@app.post("/auth/signup")
@app.post("/register")
@app.post("/signup")
def register(data: RegisterIn):
    if not _direct_register_allowed():
        raise HTTPException(status_code=403, detail="Sign-up requires email verification. Use the verification-code flow.")
    email = str(data.email).lower().strip()
    username = data.username.lower().strip()
    if not username.replace("_", "").replace("-", "").isalnum():
        raise HTTPException(
            status_code=400,
            detail="Username may contain letters, numbers, underscores and hyphens only",
        )

    params = {
        "email": email,
        "username": username,
        "full_name": (data.full_name or data.name or "").strip(),
        "password_hash": password_hash(data.password),
        "created_at": int(time.time()),
    }
    try:
        with engine.begin() as connection:
            result = connection.execute(
                text("""
                    INSERT INTO users
                        (email, username, full_name, password_hash, created_at)
                    VALUES
                        (:email, :username, :full_name, :password_hash, :created_at)
                    RETURNING id
                """),
                params,
            )
            user_id = result.scalar_one()
    except IntegrityError:
        raise HTTPException(
            status_code=409, detail="That email or username is already registered"
        )
    except SQLAlchemyError as exc:
        print(f"AURORA registration database error: {type(exc).__name__}: {exc}")
        raise HTTPException(status_code=500, detail="Account registration failed")

    token = issue_token(int(user_id), email)
    return {
        "access_token": token,
        "token_type": "bearer",
        "user": {"id": int(user_id), "email": email, "username": username},
    }


@app.post("/auth/login")
@app.post("/api/auth/login")
@app.post("/api/v1/auth/login")
@app.post("/auth/token")
@app.post("/login")
@app.post("/token")
def login(data: LoginIn):
    identity = (data.email or data.username or "").lower().strip()
    if not identity:
        raise HTTPException(status_code=400, detail="Enter your email or username")

    try:
        with engine.connect() as connection:
            user = connection.execute(
                text("""
                    SELECT id, email, username, password_hash FROM users
                    WHERE lower(email) = :identity OR lower(username) = :identity
                """),
                {"identity": identity},
            ).mappings().first()
    except SQLAlchemyError as exc:
        print(f"AURORA login database error: {type(exc).__name__}: {exc}")
        raise HTTPException(status_code=500, detail="Login service unavailable")

    # Always run one scrypt verification so response time does not reveal whether the account exists.
    password_ok = password_verify(data.password, user["password_hash"] if user else _DUMMY_HASH)
    if not user or not password_ok:
        raise HTTPException(status_code=401, detail="Incorrect email/username or password")

    token = issue_token(int(user["id"]), user["email"])
    return {
        "access_token": token,
        "token_type": "bearer",
        "user": {"id": user["id"], "email": user["email"], "username": user["username"]},
    }


