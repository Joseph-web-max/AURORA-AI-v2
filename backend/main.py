async def _search_inner(q: str):
    """Tavily -> Brave -> Wikipedia fallback. Returns [{title,url,snippet}]."""
    results = []
    async with httpx.AsyncClient(timeout=20) as c:
        if os.getenv("TAVILY_API_KEY"):
            r = await c.post("https://api.tavily.com/search", json={"api_key": os.getenv("TAVILY_API_KEY"), "query": q, "max_results": 6})
            results = [{"title": x["title"], "url": x["url"], "snippet": x.get("content", "")[:500]} for x in r.json().get("results", [])]
        elif os.getenv("BRAVE_API_KEY"):
            r = await c.get("https://api.search.brave.com/res/v1/web/search", params={"q": q, "count": 6}, headers={"X-Subscription-Token": os.getenv("BRAVE_API_KEY")})
            results = [{"title": x["title"], "url": x["url"], "snippet": x.get("description", "")[:500]} for x in r.json().get("web", {}).get("results", [])]
