_RATE: dict = {}
RATE_LIMIT = int(os.getenv("AURORA_RATE_PER_MIN", "30"))


def _rate_check(user_id: int) -> None:
    now = time.time()
    hits = [t for t in _RATE.get(user_id, []) if now - t < 60]
    if len(hits) >= RATE_LIMIT:
        raise HTTPException(status_code=429, detail="Too many requests. Please wait a moment.")
    hits.append(now)
    _RATE[user_id] = hits
    if len(_RATE) > 5000:
        for k in [k for k, v in _RATE.items() if not v or now - v[-1] > 60]:
            _RATE.pop(k, None)


def _flatten_tool_history(convo: list) -> list:
    """Final answer turn, when no tools are offered: turn tool calls/results into plain text.

    Some providers reject (or the model keeps imitating) tool calls once the request has no `tools`,
    which surfaces as "Tool choice is none, but model called a tool"."""
    out = []
    for m in convo:
        if m.get("role") == "assistant" and m.get("tool_calls"):
            names = ", ".join(str((tc.get("function") or {}).get("name", "tool")) for tc in m["tool_calls"])
            out.append({"role": "assistant", "content": f"(I used these tools: {names})"})
        elif m.get("role") == "tool":
            out.append({"role": "user", "content": "Tool result:\n" + str(m.get("content", ""))[:6000]})
        else:
            out.append(m)
    out.append({"role": "user", "content": "Tools are no longer available. Do not call any tool. Write your final reply now in plain text."})
    return out


@app.post("/ai/native/chat/completions")
async def native_chat(data: ChatIn, user=Depends(current_user)):
    base, key, model = inference_config()
    if not base or not model:
        raise HTTPException(status_code=503, detail="AURORA inference engine is not configured yet")
    _rate_check(user["id"])
    await _moderate(_user_text(next((m.content for m in reversed(data.messages) if m.role == "user"), "")))

    headers = {"Content-Type": "application/json"}
    if key:
        headers["Authorization"] = f"Bearer {key}"
    msgs = [m.model_dump() for m in data.messages][-60:]
    ref = ""
    try:
        lastq = next((m["content"] for m in reversed(msgs) if m["role"] == "user" and isinstance(m["content"], str)), "")
        ref = await asyncio.to_thread((globals().get("evo") or {}).get("retrieve", lambda q: ""), lastq)
    except Exception:
        ref = ""
    base_sys = SYSTEM_PROMPT + " Today is " + datetime.now(timezone.utc).strftime("%A, %B %d, %Y") + " (UTC)." + ref
    if msgs and msgs[0]["role"] == "system" and isinstance(msgs[0]["content"], str):
        msgs[0]["content"] = base_sys + "\n\n" + msgs[0]["content"]
    else:
        msgs.insert(0, {"role": "system", "content": base_sys})
    allowed = await asyncio.to_thread(_allowed_models)
    chosen = data.model if data.model in allowed else model
    payload = {"model": chosen, "messages": msgs, "stream": bool(data.stream),
               "max_tokens": max(1, min(data.max_tokens or 1024, 8192)),
               "temperature": max(0.0, min(data.temperature, 2.0)) if data.temperature is not None else 0.7}

    if not data.stream:
        try:
            async with httpx.AsyncClient(timeout=180) as client:
                r = await client.post(base + "/chat/completions", headers=headers, json=payload)
                r.raise_for_status()
                return r.json()
        except httpx.HTTPStatusError as exc:
            raise HTTPException(status_code=502, detail=f"Inference error {exc.response.status_code}: {exc.response.text[:400]}")
        except (httpx.HTTPError, ValueError) as exc:
            raise HTTPException(status_code=502, detail=f"Inference service unavailable: {str(exc)[:250]}")

    has_img = bool(_last_image(msgs[-3:]))
    tools_on = os.getenv("AURORA_TOOLS", "1") != "0"

    async def sse():
        # Streams tokens live. If the model calls web_search, run it here and let the model continue.
        convo = list(msgs)
        use_tools = tools_on
        use_think = data.thinking is not None
        steps = 0
        while steps < 4:
            body = dict(payload, messages=convo, stream=True)
            if use_think:
                body["chat_template_kwargs"] = {"enable_thinking": bool(data.thinking)}
            if use_tools and steps < 3:
                body["tools"] = _active_tools(has_img)
            elif steps > 0:
                body["messages"] = _flatten_tool_history(convo)
            calls: dict = {}
            try:
                async with httpx.AsyncClient(timeout=httpx.Timeout(180, connect=15)) as client:
                    async with client.stream("POST", base + "/chat/completions", headers=headers, json=body) as r:
                        if r.status_code >= 400:
                            err = (await r.aread()).decode("utf-8", "ignore")[:300]
                            if r.status_code in (400, 422):
                                if "tools" in body:
                                    use_tools = False  # provider rejects tools: retry without
                                    continue
                                if "chat_template_kwargs" in body:
                                    use_think = False  # provider rejects the think switch: retry without
                                    continue
                            if steps > 0 and "tools" not in body and "tool" in err.lower():
                                # The model still tried a tool on the final turn. Whatever the tools produced
                                # (e.g. the image) is already on screen, so end the reply cleanly.
                                yield _sse_text("\n")
                                yield "data: [DONE]\n\n"
                                return
                            yield _sse_text_error(f"Inference error {r.status_code}: {err}")
                            return
                        async for line in r.aiter_lines():
                            if not line.startswith("data:"):
                                continue
                            raw = line[5:].strip()
                            if raw == "[DONE]":
                                break
                            try:
                                choice = (json.loads(raw).get("choices") or [{}])[0]
                                d = choice.get("delta") or {}
                            except (ValueError, AttributeError):
                                continue
                            for tc in d.get("tool_calls") or []:
                                c = calls.setdefault(tc.get("index", 0), {"id": "", "name": "", "args": ""})
                                c["id"] = tc.get("id") or c["id"]
                                fn = tc.get("function") or {}
                                c["name"] += fn.get("name") or ""
                                c["args"] += fn.get("arguments") or ""
                            # Do not forward the tool_calls finish chunk: the client would treat the stream as over.
                            if not d.get("tool_calls") and choice.get("finish_reason") != "tool_calls":
                                yield "data: " + raw + "\n\n"
            except httpx.HTTPError as exc:
                yield _sse_text_error(f"Inference service unavailable: {str(exc)[:200]}")
                return
            if not calls:
                break
            steps += 1
            convo.append({"role": "assistant", "content": None, "tool_calls": [
                {"id": c["id"] or f"call_{i}", "type": "function", "function": {"name": c["name"], "arguments": c["args"] or "{}"}}
                for i, c in calls.items()]})
            for i, c in calls.items():
                try:
                    args = json.loads(c["args"] or "{}")
                except ValueError:
                    args = {}
                out = "Tool call failed."
                try:
                    if c["name"] == "run_code":
                        lang = str(args.get("language", "python"))[:20]
                        yield _sse_text(f"\u25B6 *Running {lang} code*\n\n")
                        try:
                            j = await _run_code_impl(RunIn(language=lang, code=str(args.get("code", ""))[:100_000]))
                            out = f"status: {j['status']}\nstdout:\n{j['stdout'][:3000]}\nstderr:\n{(j['stderr'] or j['compile_output'])[:2000]}"
                        except HTTPException as he:
                            out = f"Code could not run: {he.detail}"
                    elif c["name"] == "deep_research":
                        topic = str(args.get("topic", ""))[:300]
                        yield _sse_text(f"\U0001F9ED *Planning research: {topic}*\n\n")
                        plan = await _once(f"List 4 different web search queries (max 8 words each) to research: {topic}. Reply with one query per line and nothing else.", 300)
                        qs = [re.sub(r"^[\W\d_]+", "", ln).strip() for ln in plan.splitlines() if ln.strip()][:4] or [topic]
                        notes, seen = [], set()
                        for q in qs:
                            yield _sse_text(f"\U0001F50E *{q[:100]}*\n\n")
                            try:
                                found = (await _search_impl(q[:200]))["results"]
                            except Exception:
                                found = []
                            for x in found[:3]:
                                if x["url"] in seen or len(seen) >= 8:
                                    continue
                                seen.add(x["url"])
                                page = await _fetch_page(x["url"])
                                notes.append(f"[{len(seen)}] {x['title']} ({x['url']})\n{(page or x['snippet'])[:2500]}")
                        out = "\n\n".join(notes)[:24000] or "No sources found."
                    elif c["name"] == "set_reminder":
                        rt, rm = str(args.get("text", ""))[:200], max(1, min(int(args.get("minutes", 1) or 1), 60 * 24 * 30))
                        yield "data: " + json.dumps({"aurora_reminder": {"text": rt, "at": int(time.time() * 1000) + rm * 60000}}) + "\n\n"
                        out = f"Reminder set for {rm} minutes from now."
                    elif c["name"] == "edit_image":
                        src = _last_image(convo)
                        if not src:
                            out = "No image was attached."
                        else:
                            yield _sse_text("\U0001F58C *Editing image\u2026*\n\n")
                            try:
                                img = (await _edit_image_impl(EditIn(prompt=str(args.get("prompt", ""))[:2000], image=src)))["image"]
                                yield _sse_text(f"![edited image]({img})\n\n")
                                out = "The edited image is already shown to the user. Briefly describe the change."
                            except HTTPException as he:
                                out = f"Image editing failed: {he.detail}"
                    elif c["name"].startswith("plugin_"):
                        yield _sse_text(f"\U0001F50C *Using {c['name'][7:]}*\n\n")
                        out = await _call_plugin(c["name"], args)
                    elif c["name"] == "save_memory":
                        mt, mc = str(args.get("title", ""))[:80].strip(), str(args.get("content", ""))[:500].strip()
                        if mt and mc:
                            yield "data: " + json.dumps({"aurora_memory": {"title": mt, "content": mc}}) + "\n\n"
                            out = "Saved to the user's memory."
                    elif c["name"] == "generate_image":
                        pr = str(args.get("prompt", ""))[:1500]
                        yield _sse_text("\U0001F3A8 *Creating image\u2026*\n\n")
                        try:
                            img = (await _generate_image_impl(ImageIn(prompt=pr)))["image"]
                            yield _sse_text(f"![generated image]({img})\n\n")
                            out = "The image was created and is already shown to the user. Do not repeat it; briefly describe it."
                        except HTTPException as he:
                            out = f"Image generation failed: {he.detail}"
                    else:
                        q = str(args.get("query", ""))[:300]
                        yield _sse_text(f"\U0001F50D *Searching the web: {q}*\n\n")
                        res = (await _search_impl(q))["results"] if len(q) >= 2 else []
                        out = "\n".join(f"[{n}] {x['title']} ({x['url']}): {x['snippet']}" for n, x in enumerate(res, 1)) or "No results."
                except Exception:
                    pass
                convo.append({"role": "tool", "tool_call_id": c["id"] or f"call_{i}", "content": out})
        yield "data: [DONE]\n\n"

    return StreamingResponse(sse(), media_type="text/event-stream",
                             headers={"Cache-Control": "no-cache", "X-Accel-Buffering": "no"})


