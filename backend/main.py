def _hf_token(user) -> str:
    _ensure_cred_table()
    with engine.connect() as cn:
        row = cn.execute(text("SELECT hf_token FROM user_credentials WHERE user_id=:u"), {"u": user["id"]}).first()
    if not row:
        raise HTTPException(status_code=400, detail="Save your Hugging Face token first (Cloud credentials).")
    return _cred_decrypt(row[0])


def _hf(method: str, path: str, token: str = "", **kw):
    headers = kw.pop("headers", {})
    if token:
        headers["Authorization"] = "Bearer " + token
    try:
        r = httpx.request(method, HF + path, headers=headers, timeout=kw.pop("timeout", 30), **kw)
    except httpx.HTTPError as exc:
        raise HTTPException(status_code=502, detail=f"Hugging Face unreachable: {str(exc)[:200]}")
    if r.status_code in (401, 403):
        raise HTTPException(status_code=400, detail="Hugging Face rejected the token (needs write access; Jobs needs a paid account or credits).")
    if r.status_code >= 400:
        raise HTTPException(status_code=502, detail=f"Hugging Face HTTP {r.status_code}: {r.text[:250]}")
    return r


def _hf_user(token: str) -> str:
    return _hf("GET", "/api/whoami-v2", token).json()["name"]


