def _plugins() -> list:
    try:
        return [p for p in json.loads(os.getenv("AURORA_PLUGINS", "[]")) if p.get("name") and p.get("url")]
    except ValueError:
        return []


def _pname(p) -> str:
    return "plugin_" + re.sub(r"\W", "_", p["name"])[:40]


def _plugin_tools() -> list:
    return [_tool(_pname(p), str(p.get("description", ""))[:400], {k: {"type": "string", "description": str(v)[:200]} for k, v in (p.get("params") or {}).items()}, []) for p in _plugins()]


async def _call_plugin(fname: str, args: dict) -> str:
    for p in _plugins():
        if _pname(p) == fname:
            if os.getenv("AURORA_PLUGINS_ALLOW_PRIVATE") != "1":
                _check_public_url(p["url"])
            clean = {k: str(v)[:1000] for k, v in args.items() if k in (p.get("params") or {})}
            async with httpx.AsyncClient(timeout=25) as c:
                hd = dict(p.get("headers") or {})
                r = await (c.post(p["url"], headers=hd, json=clean) if str(p.get("method", "GET")).upper() == "POST" else c.get(p["url"], headers=hd, params=clean))
            return r.text[:4000]
    return "Unknown plugin."


async def _once(prompt: str, max_tokens: int = 300) -> str:
    base, key, model = inference_config()
    h = {"Content-Type": "application/json", **({"Authorization": f"Bearer {key}"} if key else {})}
    async with httpx.AsyncClient(timeout=90) as c:
        r = await c.post(base + "/chat/completions", headers=h, json={"model": model, "messages": [{"role": "user", "content": prompt}], "max_tokens": max_tokens, "temperature": 0.3})
        r.raise_for_status()
        return (r.json()["choices"][0]["message"].get("content") or "").strip()


async def _fetch_page(url: str) -> str:
    try:
        _check_public_url(url)
        async with httpx.AsyncClient(timeout=12, headers={"User-Agent": "AURORA-research/1.0"}) as c:
            r = await c.get(url)
            if r.status_code in (301, 302, 303, 307, 308) and r.headers.get("location"):
                nxt = urllib.parse.urljoin(url, r.headers["location"])
                _check_public_url(nxt)
                r = await c.get(nxt)
            if "html" not in r.headers.get("content-type", ""):
                return ""
            return _html_to_text(r.text[:400_000])[1][:3000]
    except Exception:
        return ""


def _user_text(content) -> str:
    if isinstance(content, str):
        return content
    return " ".join(p.get("text", "") for p in (content or []) if isinstance(p, dict) and p.get("type") == "text")


def _last_image(msgs: list) -> str:
    for m in reversed(msgs):
        if m.get("role") == "user" and isinstance(m.get("content"), list):
            for part in m["content"]:
                if isinstance(part, dict) and part.get("type") == "image_url":
                    return (part.get("image_url") or {}).get("url", "")
    return ""


_BLOCK = re.compile(r"(?is)\b(child|minor|underage|kid)s?\b.{0,60}\b(sex|sexual|porn|nude|naked|erotic)|\b(how to|steps to|instructions to)\b.{0,30}\b(make|build|synthesi[sz]e|cook)\b.{0,30}\b(bomb|nerve agent|sarin|bioweapon|anthrax|ricin|meth)\b")


async def _moderate(txt: str) -> None:
    flagged = bool(_BLOCK.search(txt))
    if not flagged and os.getenv("AURORA_MODERATION_KEY") and txt.strip():
        try:
            async with httpx.AsyncClient(timeout=8) as c:
                r = await c.post(os.getenv("AURORA_MODERATION_URL", "https://api.openai.com/v1/moderations"),
                                 headers={"Authorization": "Bearer " + os.getenv("AURORA_MODERATION_KEY", "")},
                                 json={"model": "omni-moderation-latest", "input": txt[:6000]})
            res = r.json()["results"][0]
            flagged = bool(res.get("categories", {}).get("sexual/minors") or res.get("categories", {}).get("violence/graphic") and res.get("category_scores", {}).get("violence/graphic", 0) > 0.9
                           or res.get("categories", {}).get("self-harm/instructions") or res.get("categories", {}).get("illicit/violent"))
        except Exception:
            pass  # fail open: moderation outage must not take the app down
    if flagged:
        raise HTTPException(status_code=400, detail="This request can't be processed because it may violate AURORA's safety policy.")


