def build_database_url() -> str:
    raw_url = os.getenv("DATABASE_URL", "sqlite:///./aurora.db").strip()
    if not raw_url:
        raise RuntimeError("DATABASE_URL is empty")

    if raw_url.startswith("postgres://"):
        raw_url = raw_url.replace("postgres://", "postgresql://", 1)

    if raw_url.startswith("postgresql://") or raw_url.startswith("postgresql+psycopg://"):
        # Explicitly use Psycopg 3, which is installed by requirements.txt.
        url = make_url(raw_url)
        url = url.set(drivername="postgresql+psycopg")
        # Supabase requires TLS. This is also safe for its Session Pooler.
        query = dict(url.query)
        query.setdefault("sslmode", "require")
        url = url.set(query=query)
        return url.render_as_string(hide_password=False)

    if raw_url.startswith("sqlite:"):
        return raw_url

    raise RuntimeError(
        "Unsupported DATABASE_URL. Use the Supabase PostgreSQL Session Pooler URI."
    )


