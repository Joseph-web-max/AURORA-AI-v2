@app.post("/foundry/knowledge/ask")
def knowledge_ask(data: KAskIn, user=Depends(current_user)):
    _ensure_knowledge_tables()
    with engine.connect() as cn:
        rows = cn.execute(text("SELECT k.body AS body, d.title AS title, d.source AS source FROM knowledge_chunks k JOIN knowledge_docs d ON d.id=k.doc_id WHERE k.user_id=:u LIMIT 6000"), {"u": user["id"]}).mappings().all()
    if not rows:
        raise HTTPException(status_code=404, detail="Your knowledge base is empty. Import something first.")
    q = set(_words(data.question))
    docs = [Counter(_words(r["body"])) for r in rows]
    n = len(docs)
    scored = []
    for r, tf in zip(rows, docs):
        s = 0.0
        for w in q:
            if tf.get(w):
                df = sum(1 for t in docs if w in t)
                s += (1 + math.log(tf[w])) * math.log(1 + n / (1 + df))
        if s > 0:
            scored.append((s / math.sqrt(sum(tf.values()) + 20), r))
    scored.sort(key=lambda x: x[0], reverse=True)
    top = scored[:5]
    if not top:
        return {"answer": "I could not find anything relevant to that question in your imported sources.", "sources": []}
    sources = [{"title": r["title"], "source": r["source"], "score": sc, "excerpt": r["body"][:500]} for sc, r in top]
    answer = None
    base, key, model = inference_config()
    if base and model:
        ctx = "\n\n".join(f"[{i + 1}] {r['title']}\n{r['body'][:1500]}" for i, (_, r) in enumerate(top))
        try:
            headers = {"Content-Type": "application/json"}
            if key:
                headers["Authorization"] = "Bearer " + key
            resp = httpx.post(base + "/chat/completions", headers=headers, timeout=120, json={
                "model": model, "stream": False, "max_tokens": 700,
                "messages": [{"role": "system", "content": "Answer using only the numbered sources. Cite them like [1]. If they do not contain the answer, say so."},
                             {"role": "user", "content": f"Sources:\n{ctx}\n\nQuestion: {data.question}"}]})
            resp.raise_for_status()
            answer = resp.json()["choices"][0]["message"]["content"]
        except Exception as exc:
            print(f"AURORA knowledge answer failed: {type(exc).__name__}: {exc}")
    if not answer:
        answer = "Most relevant passages from your sources:\n\n" + "\n\n".join(f"[{i + 1}] {s['excerpt'][:350]}" for i, s in enumerate(sources[:3]))
    return {"answer": answer, "sources": sources}


