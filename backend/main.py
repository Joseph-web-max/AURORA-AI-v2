def _cred_keys() -> tuple:
    secret = os.getenv("JWT_SECRET", "")
    if not secret:
        raise HTTPException(status_code=503, detail="Server secret is not configured.")
    base = hashlib.sha256(("aurora-credentials:" + secret).encode()).digest()
    return hmac.new(base, b"enc", hashlib.sha256).digest(), hmac.new(base, b"mac", hashlib.sha256).digest()


def _cred_crypt(data: bytes, nonce: bytes, key: bytes) -> bytes:
    out = bytearray()
    for i in range(0, len(data), 32):
        block = hmac.new(key, nonce + (i // 32).to_bytes(8, "big"), hashlib.sha256).digest()
        out += bytes(x ^ y for x, y in zip(data[i:i + 32], block))
    return bytes(out)


def _cred_encrypt(plain: str) -> str:
    ek, mk = _cred_keys()
    nonce = secrets.token_bytes(16)
    ct = _cred_crypt(plain.encode(), nonce, ek)
    tag = hmac.new(mk, nonce + ct, hashlib.sha256).digest()
    return (nonce + ct + tag).hex()


def _cred_decrypt(blob: str) -> str:
    ek, mk = _cred_keys()
    raw = bytes.fromhex(blob)
    nonce, ct, tag = raw[:16], raw[16:-32], raw[-32:]
    if not hmac.compare_digest(tag, hmac.new(mk, nonce + ct, hashlib.sha256).digest()):
        raise HTTPException(status_code=500, detail="Stored credential could not be verified.")
    return _cred_crypt(ct, nonce, ek).decode()


