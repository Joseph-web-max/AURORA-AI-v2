def _check_public_url(url: str) -> str:
    p = urllib.parse.urlparse(url.strip())
    if p.scheme not in ("http", "https") or not p.hostname:
        raise HTTPException(status_code=422, detail="Enter a full http(s) URL.")
    try:
        for info in socket.getaddrinfo(p.hostname, p.port or (443 if p.scheme == "https" else 80)):
            ip = ipaddress.ip_address(info[4][0])
            if ip.is_private or ip.is_loopback or ip.is_link_local or ip.is_reserved or ip.is_multicast:
                raise HTTPException(status_code=422, detail="That address is not a public website.")
    except socket.gaierror:
        raise HTTPException(status_code=422, detail="Could not find that website.")
    return url.strip()


def _html_to_text(raw: str) -> tuple:
    m = re.search(r"<title[^>]*>(.*?)</title>", raw, re.I | re.S)
    title = _html.unescape(re.sub(r"\s+", " ", m.group(1))).strip() if m else ""
    raw = re.sub(r"(?is)<(script|style|noscript|svg|nav|footer|header)[^>]*>.*?</\1>", " ", raw)
    raw = re.sub(r"(?i)</(p|div|h[1-6]|li|tr|section|article|pre)>|<br\s*/?>", "\n\n", raw)
    body = _html.unescape(re.sub(r"<[^>]+>", " ", raw))
    body = re.sub(r"[ \t\r\f\v]+", " ", body)
    body = re.sub(r"\n\s*\n\s*", "\n\n", body).strip()
    return title, body[:300_000]


@app.post("/foundry/knowledge/ingest-url")
def knowledge_ingest_url(data: KUrlIn, user=Depends(current_user)):
    url = _check_public_url(data.url)
    try:
        with httpx.Client(timeout=25, follow_redirects=False, headers={"User-Agent": "AURORA-Knowledge/1.0 (+personal knowledge import)"}) as c:
            p = urllib.parse.urlparse(url)
            try:
                rb = c.get(f"{p.scheme}://{p.netloc}/robots.txt")
                if rb.status_code == 200:
                    rp = urllib.robotparser.RobotFileParser()
                    rp.parse(rb.text.splitlines())
                    if not rp.can_fetch("AURORA-Knowledge", url):
                        raise HTTPException(status_code=403, detail="This site's robots.txt does not allow automated access to that page.")
            except httpx.HTTPError:
                pass
            r = None
            for _ in range(4):
                r = c.get(url)
                if r.status_code in (301, 302, 303, 307, 308) and r.headers.get("location"):
                    url = _check_public_url(urllib.parse.urljoin(url, r.headers["location"]))
                    continue
                break
            if r is None or r.status_code >= 400:
                raise HTTPException(status_code=422, detail=f"The website answered with HTTP {r.status_code if r is not None else '?'}.")
            ctype = r.headers.get("content-type", "")
            if len(r.content) > 3_000_000:
                raise HTTPException(status_code=422, detail="That page is too large to import.")
            if "html" in ctype or "xml" in ctype:
                title, body = _html_to_text(r.text)
            elif ctype.startswith("text/") or "json" in ctype:
                title, body = "", r.text[:300_000]
            else:
                raise HTTPException(status_code=422, detail="Only web pages and text files can be imported here.")
    except httpx.HTTPError as exc:
        raise HTTPException(status_code=502, detail=f"Could not fetch the page: {str(exc)[:200]}")
    return _save_knowledge(user["id"], title or urllib.parse.urlparse(url).netloc, url, body)


