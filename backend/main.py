@app.post("/foundry/training/launch")
def training_launch(data: LaunchIn, user=Depends(current_user)):
    for v in (data.base_model, data.dataset):
        if not re.fullmatch(r"[A-Za-z0-9_.-]+(/[A-Za-z0-9_.-]+)?", v):
            raise HTTPException(status_code=422, detail="Model and dataset IDs may only use letters, numbers, - _ . and one /")
    if not re.fullmatch(r"[A-Za-z0-9_.-]+/[A-Za-z0-9_.-]+", data.output_repo):
        raise HTTPException(status_code=422, detail="Output repository must be username/model-name.")
    if data.flavor not in FLAVORS:
        raise HTTPException(status_code=422, detail="Unsupported GPU size.")
    _ensure_foundry_tables()
    tok = _hf_token(user)
    ns = _hf_user(tok)
    body = {"dockerImage": "pytorch/pytorch:2.4.0-cuda12.1-cudnn9-devel", "flavor": data.flavor, "timeout": 3 * 3600,
            "command": ["bash", "-lc", 'pip install -q "trl" transformers datasets accelerate && python -c "$TRAIN_SCRIPT"'],
            "environment": {"TRAIN_SCRIPT": TRAIN_SCRIPT, "BASE_MODEL": data.base_model, "DATASET": data.dataset, "OUTPUT_REPO": data.output_repo, "MAX_STEPS": str(data.max_steps)},
            "secrets": {"HF_TOKEN": tok}}
    j = _hf("POST", f"/api/jobs/{ns}", tok, json=body, timeout=60).json()
    jid, url = j.get("id", ""), j.get("url") or f"{HF}/jobs/{ns}/{j.get('id', '')}"
    status = (j.get("status") or {}).get("stage", "SUBMITTED")
    with engine.begin() as cn:
        cn.execute(text("INSERT INTO foundry_jobs(job_id,user_id,name,namespace,status,url,output_repo,created_at) VALUES(:j,:u,:n,:ns,:s,:l,:o,:c)"),
                   {"j": jid, "u": user["id"], "n": data.name, "ns": ns, "s": status, "l": url, "o": data.output_repo, "c": time.strftime("%Y-%m-%d %H:%M", time.gmtime())})
    return {"job_id": jid, "status": status, "url": url, "output_repo": data.output_repo, "note": "Billing is per second on your Hugging Face account. Cancel the job if you do not need it."}


@app.get("/foundry/training/jobs")
def training_jobs(user=Depends(current_user)):
    _ensure_foundry_tables()
    with engine.connect() as cn:
        rows = [dict(r) for r in cn.execute(text("SELECT job_id,name,namespace,status,url,created_at FROM foundry_jobs WHERE user_id=:u ORDER BY created_at DESC LIMIT 30"), {"u": user["id"]}).mappings()]
    tok = None
    for r in rows[:8]:
        if r["status"].upper() in TERMINAL:
            continue
        try:
            tok = tok or _hf_token(user)
            st = _hf("GET", f"/api/jobs/{r['namespace']}/{r['job_id']}", tok).json().get("status", {}).get("stage", r["status"])
            r["status"] = st
            with engine.begin() as cn:
                cn.execute(text("UPDATE foundry_jobs SET status=:s WHERE job_id=:j"), {"s": st, "j": r["job_id"]})
        except HTTPException:
            pass
    return [{k: v for k, v in r.items() if k != "namespace"} for r in rows]


def _own_job(user, job_id: str) -> dict:
    _ensure_foundry_tables()
    with engine.connect() as cn:
        row = cn.execute(text("SELECT namespace FROM foundry_jobs WHERE job_id=:j AND user_id=:u"), {"j": job_id, "u": user["id"]}).mappings().first()
    if not row:
        raise HTTPException(status_code=404, detail="Job not found.")
    return dict(row)


@app.get("/foundry/training/jobs/{job_id}/logs")
def training_logs(job_id: str, user=Depends(current_user)):
    ns, tok, lines, t0 = _own_job(user, job_id)["namespace"], _hf_token(user), [], time.time()
    try:
        with httpx.stream("GET", f"{HF}/api/jobs/{ns}/{job_id}/logs", headers={"Authorization": "Bearer " + tok}, timeout=httpx.Timeout(10, read=6)) as r:
            for ln in r.iter_lines():
                if ln.startswith("data:"):
                    try:
                        lines.append(str(_json.loads(ln[5:]).get("data", "")))
                    except ValueError:
                        lines.append(ln[5:].strip())
                if time.time() - t0 > 8 or sum(map(len, lines)) > 20000:
                    break
    except httpx.HTTPError:
        pass
    return {"logs": "\n".join(lines)[-20000:], "message": "" if lines else "No logs yet. The job may still be starting."}


