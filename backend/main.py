def _direct_register_allowed() -> bool:
    """The legacy one-step /register skips email verification, which lets anyone claim an address
    (including an admin's). It is therefore off whenever email delivery is configured, unless
    AURORA_ALLOW_DIRECT_REGISTER=1 forces it on."""
    flag = os.getenv("AURORA_ALLOW_DIRECT_REGISTER", "").strip()
    if flag:
        return flag == "1"
    return not _email_delivery_configured()


