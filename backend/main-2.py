JUDGE_IDS = {"c": 50, "cpp": 54, "java": 62, "go": 60, "rust": 73, "ruby": 72, "php": 68, "bash": 46,
             "typescript": 74, "csharp": 51, "kotlin": 78, "swift": 83}


@app.post("/code/run")
async def run_code(data: RunIn, user=Depends(current_user)):
    """Run code in a remote isolated Judge0 sandbox (set JUDGE0_URL; optional JUDGE0_KEY/JUDGE0_HOST for RapidAPI)."""
    base = os.getenv("JUDGE0_URL", "").rstrip("/")
    if not base:
        raise HTTPException(status_code=501, detail="Server code sandbox is not configured (set JUDGE0_URL on the server).")
    lid = JUDGE_IDS.get(data.language.lower())
    if not lid:
        raise HTTPException(status_code=400, detail="Unsupported language for the server sandbox.")
    headers = {}
    if os.getenv("JUDGE0_KEY"):
        headers = {"X-RapidAPI-Key": os.getenv("JUDGE0_KEY"), "X-RapidAPI-Host": os.getenv("JUDGE0_HOST", "judge0-ce.p.rapidapi.com")}
    try:
        async with httpx.AsyncClient(timeout=60) as c:
            r = await c.post(base + "/submissions?base64_encoded=false&wait=true", headers=headers,
                             json={"source_code": data.code, "language_id": lid, "stdin": data.stdin, "cpu_time_limit": 5, "wall_time_limit": 10})
            r.raise_for_status()
            j = r.json()
        return {"stdout": j.get("stdout") or "", "stderr": j.get("stderr") or "", "compile_output": j.get("compile_output") or "",
                "status": (j.get("status") or {}).get("description", ""), "time": j.get("time")}
    except Exception as exc:
        print(f"AURORA code run failed: {type(exc).__name__}: {exc}")
        raise HTTPException(status_code=502, detail="The code sandbox did not respond. Check JUDGE0_URL / JUDGE0_KEY.")


