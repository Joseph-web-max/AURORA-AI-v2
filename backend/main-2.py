@app.post("/auth/register/verify")
def verify_registration_code(data: EmailCodeVerify):
    email = str(data.email).lower().strip()
    if not _consume_code(email, "register", data.code):
        raise HTTPException(status_code=400, detail="The code is incorrect or expired. Request a new one.")
    base = re.sub(r"[^a-z0-9_-]", "", email.split("@",1)[0].lower()) or "aurorauser"
    username = base[:32]
    try:
        with engine.begin() as connection:
            exists = connection.execute(text("SELECT 1 FROM users WHERE lower(email)=:email"), {"email":email}).first()
            if exists:
                raise HTTPException(status_code=409, detail="An account with this email already exists")
            taken = connection.execute(text("SELECT 1 FROM users WHERE lower(username)=:u"), {"u":username}).first()
            if taken:
                username = (base[:26] + secrets.token_hex(3))[:40]
            uid = connection.execute(text("""INSERT INTO users(email,username,full_name,password_hash,created_at)
                VALUES(:email,:username,:full_name,:password_hash,:created_at) RETURNING id"""),
                {"email":email,"username":username,"full_name":data.name.strip(),"password_hash":password_hash(data.password),"created_at":int(time.time())}).scalar_one()
    except IntegrityError:
        raise HTTPException(status_code=409, detail="That email or username is already registered")
    return {"access_token":issue_token(int(uid),email),"token_type":"bearer","user":{"id":int(uid),"email":email,"username":username}}


