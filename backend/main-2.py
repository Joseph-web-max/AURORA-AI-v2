def _email_code_hash(code: str) -> str:
    return hmac.new(JWT_SECRET.encode(), code.encode(), hashlib.sha256).hexdigest()


def _mail_sender() -> tuple:
    """Return (email, display_name) for the From address."""
    raw = (os.getenv("MAIL_FROM") or os.getenv("SMTP_FROM") or os.getenv("SMTP_USER") or "").strip()
    m = re.match(r"^\s*(.*?)\s*<([^>]+)>\s*$", raw)
    if m:
        return m.group(2).strip(), (m.group(1).strip().strip('"') or "AURORA AI")
    return raw, "AURORA AI"


def _send_via_brevo(to_email: str, subject: str, body: str, api_key: str) -> None:
    sender_email, sender_name = _mail_sender()
    if not sender_email:
        raise RuntimeError("MAIL_FROM is not set (must be a sender verified in Brevo)")
    response = httpx.post(
        "https://api.brevo.com/v3/smtp/email",
        headers={"api-key": api_key, "accept": "application/json", "content-type": "application/json"},
        json={
            "sender": {"email": sender_email, "name": sender_name},
            "to": [{"email": to_email}],
            "subject": subject,
            "textContent": body,
        },
        timeout=20,
    )
    if response.status_code >= 300:
        raise RuntimeError(f"Brevo HTTP {response.status_code}: {response.text[:300]}")


def _send_via_resend(to_email: str, subject: str, body: str, api_key: str) -> None:
    sender_email, sender_name = _mail_sender()
    if not sender_email:
        sender_email = "onboarding@resend.dev"
    response = httpx.post(
        "https://api.resend.com/emails",
        headers={"Authorization": f"Bearer {api_key}", "Content-Type": "application/json"},
        json={"from": f"{sender_name} <{sender_email}>", "to": [to_email], "subject": subject, "text": body},
        timeout=20,
    )
    if response.status_code >= 300:
        raise RuntimeError(f"Resend HTTP {response.status_code}: {response.text[:300]}")


def _send_via_smtp(to_email: str, subject: str, body: str) -> None:
    host = os.getenv("SMTP_HOST", "")
    user = os.getenv("SMTP_USER", "")
    password = os.getenv("SMTP_PASSWORD", "")
    sender = os.getenv("SMTP_FROM", user)
    port = int(os.getenv("SMTP_PORT", "587"))
    msg = EmailMessage()
    msg["Subject"] = subject
    msg["From"] = sender
    msg["To"] = to_email
    msg.set_content(body)
    with smtplib.SMTP(host, port, timeout=20) as server:
        server.starttls()
        server.login(user, password)
        server.send_message(msg)


def _send_email(to_email: str, subject: str, body: str) -> None:
    """Send mail over HTTPS (works on Render free tier, which blocks SMTP ports).

    Provider order: Brevo (BREVO_API_KEY) -> Resend (RESEND_API_KEY) -> SMTP (paid Render only).
    """
    brevo_key = os.getenv("BREVO_API_KEY", "").strip()
    resend_key = os.getenv("RESEND_API_KEY", "").strip()
    smtp_ready = all([os.getenv("SMTP_HOST"), os.getenv("SMTP_USER"), os.getenv("SMTP_PASSWORD")])
    if not (brevo_key or resend_key or smtp_ready):
        raise HTTPException(status_code=503, detail="Email delivery is not configured on the AURORA server yet")
    try:
        if brevo_key:
            _send_via_brevo(to_email, subject, body, brevo_key)
        elif resend_key:
            _send_via_resend(to_email, subject, body, resend_key)
        else:
            _send_via_smtp(to_email, subject, body)
    except Exception as exc:
        print(f"AURORA email delivery failed: {type(exc).__name__}: {exc}")
        detail = "Could not send the email. Check the server email settings."
        # Set EMAIL_DEBUG=1 in Render to see the real reason on screen; remove it afterwards.
        if os.getenv("EMAIL_DEBUG", "").strip() == "1":
            detail += f" [{type(exc).__name__}: {str(exc)[:240]}]"
        raise HTTPException(status_code=502, detail=detail)


def _store_code(email: str, purpose: str, code: str) -> None:
    now = int(time.time())
    with engine.begin() as connection:
        connection.execute(text("""INSERT INTO auth_codes(email,purpose,code_hash,expires_at,created_at)
            VALUES(:email,:purpose,:code_hash,:expires_at,:created_at)
            ON CONFLICT(email,purpose) DO UPDATE SET code_hash=:code_hash,expires_at=:expires_at,created_at=:created_at"""),
            {"email":email,"purpose":purpose,"code_hash":_email_code_hash(code),"expires_at":now+600,"created_at":now})


def _consume_code(email: str, purpose: str, code: str) -> bool:
    with engine.begin() as connection:
        row = connection.execute(text("SELECT code_hash,expires_at FROM auth_codes WHERE email=:email AND purpose=:purpose"),
                                 {"email":email,"purpose":purpose}).mappings().first()
        if not row or int(row["expires_at"]) < int(time.time()) or not hmac.compare_digest(row["code_hash"], _email_code_hash(code)):
            return False
        connection.execute(text("DELETE FROM auth_codes WHERE email=:email AND purpose=:purpose"), {"email":email,"purpose":purpose})
        return True


