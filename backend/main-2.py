def init_db() -> None:
    """Create the application users table using PostgreSQL- or SQLite-compatible DDL."""
    if engine.dialect.name == "postgresql":
        ddl = """
            CREATE TABLE IF NOT EXISTS users (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                email VARCHAR(320) NOT NULL UNIQUE,
                username VARCHAR(40) NOT NULL UNIQUE,
                full_name VARCHAR(100) NOT NULL DEFAULT '',
                password_hash TEXT NOT NULL,
                created_at BIGINT NOT NULL
            )
        """
    elif engine.dialect.name == "sqlite":
        ddl = """
            CREATE TABLE IF NOT EXISTS users (
                id INTEGER PRIMARY KEY AUTOINCREMENT,
                email TEXT NOT NULL UNIQUE,
                username TEXT NOT NULL UNIQUE,
                full_name TEXT NOT NULL DEFAULT '',
                password_hash TEXT NOT NULL,
                created_at INTEGER NOT NULL
            )
        """
    else:
        raise RuntimeError(f"Unsupported database dialect: {engine.dialect.name}")

    with engine.begin() as connection:
        connection.execute(text(ddl))
        if engine.dialect.name == "postgresql":
            connection.execute(text("""CREATE TABLE IF NOT EXISTS auth_codes (
                email VARCHAR(320) NOT NULL, purpose VARCHAR(20) NOT NULL,
                code_hash TEXT NOT NULL, expires_at BIGINT NOT NULL,
                created_at BIGINT NOT NULL, PRIMARY KEY(email, purpose))"""))
        else:
            connection.execute(text("""CREATE TABLE IF NOT EXISTS auth_codes (
                email TEXT NOT NULL, purpose TEXT NOT NULL, code_hash TEXT NOT NULL,
                expires_at INTEGER NOT NULL, created_at INTEGER NOT NULL,
                PRIMARY KEY(email, purpose))"""))


