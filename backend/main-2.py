@app.post("/auth/google")
async def google_sign_in(data: GoogleLoginIn):
    client_id = os.getenv("GOOGLE_CLIENT_ID", "").strip()
    if not client_id:
        raise HTTPException(status_code=503, detail="Google sign-in is not configured on the AURORA server")
    try:
        async with httpx.AsyncClient(timeout=15) as client:
            response = await client.get("https://oauth2.googleapis.com/tokeninfo", params={"id_token":data.id_token})
        if response.status_code != 200:
            raise ValueError("Google token invalid")
        info = response.json()
        if info.get("aud") != client_id or info.get("email_verified") not in (True, "true"):
            raise ValueError("Google account could not be verified")
        email = str(info.get("email", "")).lower().strip()
        name = str(info.get("name", "")).strip()
        if not email:
            raise ValueError("Google did not provide an email")
    except Exception:
        raise HTTPException(status_code=401, detail="Google sign-in could not verify this account")
    username = re.sub(r"[^a-z0-9_-]", "", email.split("@",1)[0])[:32] or "googleuser"
    with engine.begin() as connection:
        user = connection.execute(text("SELECT id,username FROM users WHERE lower(email)=:email"), {"email":email}).mappings().first()
        if user:
            uid = int(user["id"])
        else:
            taken = connection.execute(text("SELECT 1 FROM users WHERE lower(username)=:u"), {"u":username}).first()
            if taken: username=(username[:26]+secrets.token_hex(3))[:40]
            uid = int(connection.execute(text("""INSERT INTO users(email,username,full_name,password_hash,created_at)
                VALUES(:email,:username,:full_name,:password_hash,:created_at) RETURNING id"""),
                {"email":email,"username":username,"full_name":name,"password_hash":password_hash(secrets.token_urlsafe(32)),"created_at":int(time.time())}).scalar_one())
    return {"access_token":issue_token(uid,email),"token_type":"bearer","user":{"id":uid,"email":email,"username":username}}


